#!/usr/bin/env bash
# Rebuilds display_mode.exe from display_mode.c and writes it, base64, into
# WineKit's WineDisplayMode+Program.swift, which the wrapp writes out and runs
# for a launch's --wine.display-mode (docs/wine-in-process-helpers.md#a-display-mode-the-launch-sets).
# Needs MinGW (`brew install mingw-w64`); a normal build doesn't, as the bytes
# are committed.
set -euo pipefail
cd "$(dirname "$0")"
out="$(mktemp -d)"
trap 'rm -rf "$out"' EXIT

# No C runtime: it calls ChangeDisplaySettingsExW and prints one line, and
# without one it's 3.5 KB.
i686-w64-mingw32-gcc -Os -s -nostdlib -ffreestanding -fno-stack-protector -fno-asynchronous-unwind-tables \
    -e _start -Wl,--subsystem,console -Wl,--no-insert-timestamp -o "$out/display_mode.exe" display_mode.c -lkernel32 -luser32 -lgdi32

swift_file=../Sources/WineKit/WineDisplayMode+Program.swift
{
    echo "//"
    echo "//  WineDisplayMode+Program.swift"
    echo "//  WineKit"
    echo "//"
    echo "//  Generated by Packages/Modules/wine/DisplayMode/regenerate.sh from"
    echo "//  display_mode.c: don't edit by hand."
    echo
    echo "nonisolated extension WineDisplayMode {"
    echo "    /// display_mode.exe, a 32-bit Windows console program, base64."
    echo "    static let programBase64 = \"\"\""
    base64 -i "$out/display_mode.exe" | fold -w 120 | sed 's/^/        /'
    echo "        \"\"\""
    echo "}"
} > "$swift_file"
echo "wrote $swift_file ($(wc -c < "$out/display_mode.exe" | tr -d ' ') bytes)"
