#!/bin/sh
# Rebuilds Sources/WrappBuilder/Bundles/AjvScript.swift: entry.js and ajv,
# at the versions package-lock.json pins, bundled into one script and kept
# as a Swift string, with the licence of every package bundled into it at
# its head. README.md has when and why.
set -eu
cd "$(dirname "$0")"
npm ci --ignore-scripts
bundle=$(mktemp -d)
trap 'rm -rf "$bundle" node_modules' EXIT
npx --no-install esbuild entry.js --bundle --minify --format=iife --target=safari17 \
    --legal-comments=eof --outfile="$bundle/ajv.min.js"
out=../Sources/WrappBuilder/Bundles/AjvScript.swift
{
    echo "// Generated by Packages/WrappBuilder/JavaScript/build.sh: don't edit."
    echo
    echo "/// ajv, bundled with entry.js, as SchemaValidator runs it."
    echo "nonisolated let ajvScript = #####\"\"\""
    echo "/*"
    for package in ajv fast-deep-equal fast-uri json-schema-traverse require-from-string; do
        echo "== $package $(node -p "require('./node_modules/$package/package.json').version")"
        echo
        sed 's#\*/#* /#g' node_modules/"$package"/LICENSE* 2>/dev/null || sed 's#\*/#* /#g' node_modules/"$package"/license
        echo
    done
    echo "*/"
    cat "$bundle/ajv.min.js"
    echo "\"\"\"#####"
} > "$out"
