import Foundation
import WrappBuilder

/// Second Chance's `EMIT` strings (`SecondChance/Resources/emit-vocabulary.yaml`)
/// as Swift, for the app, which reads no YAML for them: its phases, in
/// order, and its substep keys.
enum EmitVocabularySource {
    static let vocabularyPath = "SecondChance/Resources/emit-vocabulary.yaml"
    static let path = "SecondChance/Models/EmitVocabulary+Generated.swift"

    static func source(for vocabulary: EmitVocabulary) -> String {
        func values(_ pattern: String, _ name: String) -> [String] {
            guard case .oneOf(let values)? = vocabulary.strings.first(where: { $0.pattern == pattern })?.values[name] else { return [] }
            return values
        }
        func list(_ values: [String]) -> String { "[" + values.map { "\"\($0)\"" }.joined(separator: ", ") + "]" }
        return """
        // Generated by `sc generate` from \(vocabularyPath). Don't edit: change
        // the YAML and run `sc generate`.

        /// The `EMIT` strings Second Chance reads (docs/wrappfile.md#emit).
        nonisolated enum SecondChanceEmits {
            static let prefix = "\(vocabulary.prefix)"
            /// `\(vocabulary.prefix)phase.<phase>`, in the order a build reaches them.
            static let phases = \(list(values("\(vocabulary.prefix)phase.<phase>", "phase")))
            /// `\(vocabulary.prefix)substep.<key>`.
            static let substeps = \(list(values("\(vocabulary.prefix)substep.<key>", "key")))
        }

        """
    }
}
